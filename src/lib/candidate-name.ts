/**
 * Имя кандидата — единственная строка, которую посторонний человек передаёт в систему, и
 * она попадает в инструкции голосового агента. Значит это точка внедрения: перевод строки
 * плюс «ignore previous instructions» превращает поле имени в канал управления агентом.
 *
 * Отсюда три правила. Никаких переводов строк и управляющих символов — они дают возможность
 * открыть новый блок инструкций. Разрешены буквы любого алфавита, цифры и та пунктуация,
 * что встречается в именах: имена бывают на любом языке, отсекать по латинице нельзя.
 * И жёсткий предел длины: без него имя на сто килобайт раздувает промпт и счёт за него.
 */
export const MAX_CANDIDATE_NAME = 80

export function sanitizeCandidateName(raw: unknown): string {
  if (typeof raw !== 'string') return ''
  return raw
    .normalize('NFC')
    // Управляющие символы и любые переводы строк — в пробел.
    .replace(/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]+/gu, ' ')
    // Оставляем буквы, цифры, пробел и пунктуацию имён: дефис, апостроф, точка.
    .replace(/[^\p{L}\p{N} \-'’.]+/gu, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_CANDIDATE_NAME)
}
